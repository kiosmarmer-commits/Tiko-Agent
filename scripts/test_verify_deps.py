class ParseLockfileTest(unittest.TestCase):
    def test_parse_hosted_packages_only(self):
        with tempfile.TemporaryDirectory() as tmp:
            lock = Path(tmp) / "pubspec.lock"
            lock.write_text(LOCK_SAMPLE)
            pkgs = vd.parse_lockfile(lock)
        self.assertEqual([p["name"] for p in pkgs], ["http", "meta"])
        self.assertEqual(pkgs[0]["version"], "1.2.0")
        self.assertEqual(pkgs[0]["sha256"], "a" * 64)
        self.assertTrue(all(p["url"] == "https://pub.dev" for p in pkgs))

    def test_collect_deduplicates_across_lockfiles(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "a").mkdir()
            (root / "a" / "pubspec.lock").write_text(LOCK_SAMPLE)
            (root / "b").mkdir()
            (root / "b" / "pubspec.lock").write_text(LOCK_SAMPLE)
            pkgs = vd.collect_locked_packages(root)
        self.assertEqual(len(pkgs), 2)
        self.assertEqual(pkgs[0]["name"], "http")


