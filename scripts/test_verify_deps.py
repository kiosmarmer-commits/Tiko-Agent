class AuditLockedTest(unittest.TestCase):
    def _pkg(self, sha="a" * 64):
        return {"name": "http", "version": "1.2.0", "sha256": sha, "url": "https://pub.dev", "lockfile": "x"}

    def test_vulnerable_package_fails(self):
        orig_post, orig_get = vd.http_post_json, vd.http_get_json
        vd.http_post_json = lambda url, payload, timeout=60: {
            "results": [{"vulns": [{"id": "GHSA-9v85-q87q-g4vg"}]} for _ in payload["queries"]]
        }
        vd.http_get_json = lambda url, timeout=20: (
            {"affected": [{"package": {"ecosystem": "Pub", "name": "http"},
                           "ranges": [{"events": [{"fixed": "1.2.1"}]}]}]}
            if "vulns/" in url
            else {"latest": {}, "versions": [{"version": "1.2.0",
                                              "published": "2026-01-01T00:00:00.000Z",
                                              "archive_sha256": "a" * 64}]}
        )
        try:
            report = vd.audit_locked([self._pkg()], NOW, 7, 365)
        finally:
            vd.http_post_json, vd.http_get_json = orig_post, orig_get
        self.assertEqual(len(report["failures"]), 1)
        self.assertIn("GHSA-9v85-q87q-g4vg", report["failures"][0])
        self.assertIn("1.2.1", report["failures"][0])

    def test_sha_mismatch_fails(self):
        orig_post, orig_get = vd.http_post_json, vd.http_get_json
        vd.http_post_json = lambda url, payload, timeout=60: {"results": [{} for _ in payload["queries"]]}
        vd.http_get_json = lambda url, timeout=20: {
            "versions": [{"version": "1.2.0", "published": "2026-01-01T00:00:00.000Z",
                          "archive_sha256": "c" * 64}]
        }
        try:
            report = vd.audit_locked([self._pkg()], NOW, 7, 365)
        finally:
            vd.http_post_json, vd.http_get_json = orig_post, orig_get
        self.assertEqual(len(report["failures"]), 1)
        self.assertIn("SHA-MISMATCH", report["rows"][0][3])

    def test_fresh_release_warns_not_fails(self):
        orig_post, orig_get = vd.http_post_json, vd.http_get_json
        vd.http_post_json = lambda url, payload, timeout=60: {"results": [{} for _ in payload["queries"]]}
        vd.http_get_json = lambda url, timeout=20: {
            "versions": [{"version": "1.2.0", "published": "2026-11-14T00:00:00.000Z",
                          "archive_sha256": "a" * 64}]
        }
        try:
            report = vd.audit_locked([self._pkg()], NOW, 7, 365)
        finally:
            vd.http_post_json, vd.http_get_json = orig_post, orig_get
        self.assertEqual(report["failures"], [])
        self.assertEqual(len(report["warnings"]), 1)
        self.assertIn("terlalu baru", report["warnings"][0])

    def test_unknown_version_fails(self):
        orig_post, orig_get = vd.http_post_json, vd.http_get_json
        vd.http_post_json = lambda url, payload, timeout=60: {"results": [{} for _ in payload["queries"]]}
        vd.http_get_json = lambda url, timeout=20: {"versions": []}
        try:
            report = vd.audit_locked([self._pkg()], NOW, 7, 365)
        finally:
            vd.http_post_json, vd.http_get_json = orig_post, orig_get
        self.assertEqual(len(report["failures"]), 1)
        self.assertIn("TIDAK-ADA-DI-REGISTRY", report["rows"][0][3])

    def test_osv_outage_fails_closed(self):
        def boom(url, payload, timeout=60):
            raise OSError("osv down")

        orig_post, orig_get = vd.http_post_json, vd.http_get_json
        vd.http_post_json = boom
        vd.http_get_json = lambda url, timeout=20: {
            "versions": [{"version": "1.2.0", "published": "2026-01-01T00:00:00.000Z",
                          "archive_sha256": "a" * 64}]
        }
        try:
            report = vd.audit_locked([self._pkg()], NOW, 7, 365)
        finally:
            vd.http_post_json, vd.http_get_json = orig_post, orig_get
        self.assertTrue(any("fail-closed" in f for f in report["failures"]))


class MainExitCodeTest(unittest.TestCase):
    def test_strict_exit_1_on_failures(self):
        with tempfile.TemporaryDirectory() as tmp:
            (Path(tmp) / "pubspec.lock").write_text(LOCK_SAMPLE)
            orig_collect, orig_audit = vd.collect_locked_packages, vd.audit_locked
            vd.collect_locked_packages = lambda root: [{"name": "http", "version": "1.2.0",
                                                        "sha256": "a" * 64, "url": "", "lockfile": ""}]
            vd.audit_locked = lambda *a, **k: {"failures": ["x"], "warnings": [], "infos": [], "rows": []}
            try:
                rc = vd.main(["--strict", "--root", tmp])
            finally:
                vd.collect_locked_packages, vd.audit_locked = orig_collect, orig_audit
        self.assertEqual(rc, 1)

    def test_clean_exit_0(self):
        orig_collect, orig_audit = vd.collect_locked_packages, vd.audit_locked
        vd.collect_locked_packages = lambda root: [{"name": "http", "version": "1.2.0",
                                                    "sha256": "a" * 64, "url": "", "lockfile": ""}]
        vd.audit_locked = lambda *a, **k: {"failures": [], "warnings": [], "infos": [], "rows": []}
        try:
            rc = vd.main(["--root", "/nonexistent"])
        finally:
            vd.collect_locked_packages, vd.audit_locked = orig_collect, orig_audit
        self.assertEqual(rc, 0)


