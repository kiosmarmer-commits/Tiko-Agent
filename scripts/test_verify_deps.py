class OsvBatchScanTest(unittest.TestCase):
    def test_chunking_and_hit_collection(self):
        calls = []

        def fake_post(url, payload, timeout=60):
            calls.append(payload)
            idx = len(calls) - 1
            return {"results": [
                {"vulns": [{"id": f"GHSA-{idx}"}]} if j == 0 else {}
                for j, _ in enumerate(payload["queries"])
            ]}

        orig = vd.http_post_json
        vd.http_post_json = fake_post
        try:
            pkgs = [{"name": f"p{i}", "version": "1.0.0"} for i in range(1001)]
            hits = vd.osv_batch_scan(pkgs)
        finally:
            vd.http_post_json = orig
        self.assertEqual(len(calls), 2)
        self.assertEqual(len(calls[0]["queries"]), 1000)
        self.assertEqual(len(calls[1]["queries"]), 1)
        self.assertEqual(hits[("p0", "1.0.0")], ["GHSA-0"])
        self.assertEqual(hits[("p1000", "1.0.0")], ["GHSA-1"])

    def test_result_count_mismatch_raises(self):
        orig = vd.http_post_json
        vd.http_post_json = lambda url, payload, timeout=60: {"results": []}
        try:
            with self.assertRaises(ValueError):
                vd.osv_batch_scan([{"name": "http", "version": "1.2.0"}])
        finally:
            vd.http_post_json = orig


