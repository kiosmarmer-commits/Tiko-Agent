import 'dart:io';

import 'package:agent_providers/agent_providers.dart' show findProviderPreset;
import 'package:path/path.dart' as p;

import 'config_store.dart';
import 'tiko_config.dart';

/// Collected onboarding answers: pure data, no I/O. Secrets live in [env]
/// and are never written into the YAML config — the config references them
/// as SecretRef `env:<VAR>` (fail-closed convention of [TikoConfig]).
class OnboardingProfile {
  OnboardingProfile({
    required this.providerType,
    required this.workspace,
    this.providerId = 'main',
    this.baseUrl,
    this.model,
    this.apiKeyEnvVar,
    Map<String, String> env = const {},
  })  : assert(providerId.isNotEmpty),
        assert(workspace.isNotEmpty),
        env = Map.unmodifiable(env);

  /// Built-in type (`mock`, `ollama_native`, `openai_compat`, `anthropic`,
  /// `gemini`, …), a provider preset id (e.g. `openai`, `deepseek`), or a
  /// Hermes-parity transport (`openai_responses`, `azure_openai`, `bedrock`).
  final String providerType;
  final String providerId;
  final String workspace;
  final String? baseUrl;
  final String? model;

  /// Env var name holding the API key (e.g. `OPENAI_API_KEY`); null when the
  /// provider needs no key (mock, local Ollama).
  final String? apiKeyEnvVar;

  /// Gateway and provider credentials written to the 0600 env file.
  final Map<String, String> env;

  static String defaultApiKeyVar(String providerType) {
    final preset = providerType.replaceAll(RegExp(r'[^a-z0-9]'), '_');
    return '${preset.toUpperCase()}_API_KEY';
  }
}

/// Interactive onboarding (Hermes-parity `setup --portal` analog): one flow
/// that collects provider credentials and gateway tokens, then writes
/// (1) a validated `config.yaml` via [ConfigStore] with secret refs only and
/// (2) a 0600 env file with every collected secret.
abstract final class OnboardingWizard {
  /// Renders the full config YAML for the profile. Throws [ArgumentError]
  /// for an unknown provider type.
  static String renderConfigYaml(OnboardingProfile profile) {
    final type = profile.providerType;
    final isMock = type == 'mock';
    final isOllama = type == 'ollama_native' || type == 'ollama';
    if (!isMock && !isOllama) {
      if (!TikoConfig.knownProviderTypes.contains(type) &&
          findProviderPreset(type) == null) {
        throw ArgumentError.value(
          type,
          'providerType',
          'tipe tidak dikenal (bukan tipe bawaan atau id preset)',
        );
      }
    }
    String quote(String value) =>
        '"${value.replaceAll('\\', r'\\').replaceAll('"', r'\"').replaceAll('\r', r'\r').replaceAll('\n', r'\n').replaceAll('\t', r'\t')}"';

    final providerId = isMock
        ? 'mock'
        : (isOllama ? 'ollama_local' : profile.providerId);
    final lines = <String>[
      '# Generated by `tiko setup --interactive`; schema is validated by TikoConfig.',
      'profile: default',
      'workspace: ${quote(profile.workspace)}',
      'logs_dir: "logs"',
      'agent:',
      '  max_iterations: 12',
      '  max_tokens_per_task: 60000',
      '  max_wall_clock_sec: 300',
      '  max_tool_calls: 30',
      'providers:',
      '  default_chat: $providerId',
      '  tiers: {}',
      '  chat:',
      if (isMock) ...[
        '    mock:',
        '      type: mock',
        '      enabled: true',
      ],
      if (isOllama) ...[
        '    ollama_local:',
        '      type: ollama_native',
        '      base_url: ${quote(profile.baseUrl ?? 'http://127.0.0.1:11434')}',
        '      model: ${quote(profile.model ?? 'qwen2.5:3b')}',
        '      enabled: true',
      ],
      if (!isMock && !isOllama) ...[
        '    $providerId:',
        '      type: $type',
        if (profile.baseUrl != null)
          '      base_url: ${quote(profile.baseUrl!)}',
        if (profile.model != null) '      model: ${quote(profile.model!)}',
        if (profile.apiKeyEnvVar != null)
          '      api_key: "env:${profile.apiKeyEnvVar}"',
        '      enabled: true',
      ],
      'security:',
      '  mode: ask',
      '  shell_allowlist: ["ls", "pwd", "echo", "git status"]',
      '  require_confirm: ["write_file", "patch_file", "shell", "http_request"]',
      'storage:',
      '  data_dir: "data"',
      '  db_path: "data/agent.db"',
      'api:',
      '  port: 8787',
      'search:',
      '  searxng_base_url: "http://127.0.0.1:8080"',
      'http:',
      '  domain_allowlist: []',
      'mcp:',
      '  servers: []',
    ];
    return '${lines.join('\n')}\n';
  }

  /// Renders the shell env file body (`export KEY=value` lines, sorted).
  /// Values containing newlines are rejected — they cannot be represented
  /// safely in a sourced env file.
  static String renderEnvFile(OnboardingProfile profile) {
    final keys = profile.env.keys.toList()..sort();
    final lines = <String>[
      '# Generated by `tiko setup --interactive` (permission 600).',
      '# Source sebelum menjalankan agentd: source $envFileName',
    ];
    for (final key in keys) {
      final value = profile.env[key]!;
      if (value.contains('\n') || value.contains('\r')) {
        throw ArgumentError.value(key, 'env', 'nilai tidak boleh mengandung newline');
      }
      lines.add('export $key=$value');
    }
    return '${lines.join('\n')}\n';
  }

  static const envFileName = 'gateway.env';

  /// Writes the validated config (via [ConfigStore], revisioned) and the
  /// 0600 env file. Throws [StateError] when the config exists and
  /// [force] is false, and [ArgumentError] when validation fails.
  static Future<({String configPath, String envPath})> writeAll({
    required String configPath,
    required String dataDir,
    required OnboardingProfile profile,
    bool force = false,
  }) async {
    final yaml = renderConfigYaml(profile);
    final (_, issues) = TikoConfig.parse(yaml);
    final fatal = issues.where((i) => i.fatal).toList();
    if (fatal.isNotEmpty) {
      throw ArgumentError('config hasil onboarding tidak valid: $fatal');
    }
    final file = File(configPath);
    if (await file.exists() && !force) {
      throw StateError('config sudah ada: ${p.absolute(configPath)}');
    }
    await file.parent.create(recursive: true);
    final envPath = p.join(dataDir, envFileName);
    await _writeSecretFile(envPath, renderEnvFile(profile));
    final store = ConfigStore(
      configPath: configPath,
      revisionsDir: p.join(dataDir, 'config_revisions'),
    );
    final result = await store.writeFull(yaml, note: 'setup interactive');
    final fatalWrite = result.issues.where((i) => i.fatal).toList();
    if (fatalWrite.isNotEmpty) {
      throw StateError('gagal menyimpan config: $fatalWrite');
    }
    return (configPath: p.absolute(configPath), envPath: envPath);
  }

  static Future<void> _writeSecretFile(String target, String content) async {
    final directory = Directory(p.dirname(target));
    await directory.create(recursive: true);
    final temporary = File('$target.tmp');
    await temporary.writeAsString(content, flush: true);
    if (!Platform.isWindows) {
      final result = await Process.run('chmod', ['600', temporary.path]);
      if (result.exitCode != 0) {
        try {
          await temporary.delete();
        } catch (_) {}
        throw StateError(
          'Tidak dapat mengamankan permission file env: ${result.stderr}',
        );
      }
    }
    try {
      await temporary.rename(target);
    } on FileSystemException {
      final existing = File(target);
      if (await existing.exists()) await existing.delete();
      await temporary.rename(target);
    }
  }
}
