import 'package:agent_core/agent_core.dart';

class MemorySearchTool implements Tool {
  MemorySearchTool(this.store);
  final MemoryStore store;

  @override
  ToolSpec get spec => const ToolSpec(
    name: 'memory_search',
    description: 'Cari fakta/preferensi di memori jangka panjang.',
    inputSchema: {
      'type': 'object',
      'properties': {
        'query': {'type': 'string'},
        'k': {'type': 'integer'},
      },
      'required': ['query'],
    },
    risk: 'low',
  );

  @override
  Future<ToolResult> run(Map<String, dynamic> args, ToolContext ctx) async {
    final q = (args['query'] as String?)?.trim() ?? '';
    if (q.isEmpty) {
      return const ToolResult(
        callId: '',
        content: 'query wajib',
        isError: true,
      );
    }
    final k = (args['k'] as num?)?.toInt() ?? 6;
    final hits = ctx.session.userKey.trim().isEmpty || store is! OwnerScopedMemoryStore
        ? const <MemoryHit>[]
        : await (store as OwnerScopedMemoryStore).searchForOwner(
            q, ownerKey: ctx.session.userKey, k: k);
    if (hits.isEmpty) {
      return const ToolResult(callId: '', content: '(tidak ada hasil memori)');
    }
    final lines = hits
        .map((h) => '- [${h.score.toStringAsFixed(2)}; ${h.provenance.name}] ${h.text}')
        .join('\n');
    // Search results are evidence, not instructions. Neutralize any attempt
    // inside stored text to close or forge the untrusted-data envelope.
    final safeLines = lines
        .replaceAll('</untrusted_data', '<\\/untrusted_data')
        .replaceAll('<untrusted_data', '<\\untrusted_data');
    return ToolResult(
      callId: '',
      content: '<untrusted_data source="memory-search">\n$safeLines\n</untrusted_data>',
    );
  }
}

class MemoryAddTool implements Tool {
  MemoryAddTool(this.store);
  final MemoryStore store;

  @override
  ToolSpec get spec => const ToolSpec(
    name: 'memory_add',
    description:
        'Simpan catatan kandidat (maks 300 karakter, tanpa rahasia). Hanya fakta yang benar-benar berasal dari pesan user dan dikonfirmasi eksplisit yang dapat menjadi memori tepercaya.',
    inputSchema: {
      'type': 'object',
      'properties': {
        'text': {'type': 'string'},
        'kind': {
          'type': 'string',
          'description': 'fact | preference | episode',
        },
        'importance': {'type': 'number'},
      },
      'required': ['text'],
    },
    risk: 'low',
  );

  @override
  Future<ToolResult> run(Map<String, dynamic> args, ToolContext ctx) async {
    final text = (args['text'] as String?)?.trim() ?? '';
    if (text.isEmpty) {
      return const ToolResult(callId: '', content: 'text wajib', isError: true);
    }
    await store.upsertFact(
      Fact(
        id: '',
        text: text,
        kind: (args['kind'] as String?) ?? 'fact',
        importance: (args['importance'] as num?)?.toDouble() ?? 0.7,
        sourceSession: ctx.session.id,
        ownerKey: ctx.session.userKey,
        createdAt: DateTime.now().toUtc(),
        // Tool arguments are generated by a model and are not proof that
        // the user asserted the same fact. Keep these notes pending/untrusted.
        provenance: Provenance.agent,
        confidence: 0.3,
        ttlDays: 14,
        state: 'pending',
      ),
    );
    return const ToolResult(callId: '', content: 'Catatan kandidat disimpan untuk ditinjau; belum menjadi memori tepercaya.');
  }
}
