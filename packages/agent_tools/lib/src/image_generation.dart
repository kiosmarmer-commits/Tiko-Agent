/// Image generation provider configuration
class ImageGenerationProvider {
  const ImageGenerationProvider({
    required this.name,
    required this.baseUrl,
    required this.apiKeyEnvVar,
    this.defaultModel,
    this.timeout = const Duration(seconds: 60),
    this.maxRetries = 3,
  });

  final String name;
  final String baseUrl;
  final String apiKeyEnvVar;
  final String? defaultModel;
  final Duration timeout;
  final int maxRetries;

  Map<String, dynamic> toJson() => {
        'name': name,
        'baseUrl': baseUrl,
        'apiKeyEnvVar': apiKeyEnvVar,
        'defaultModel': defaultModel,
        'timeout': timeout.inSeconds,
        'maxRetries': maxRetries,
      };

  factory ImageGenerationProvider.fromJson(Map<String, dynamic> json) {
    return ImageGenerationProvider(
      name: json['name'] as String,
      baseUrl: json['baseUrl'] as String? ?? 'https://fal.run',
      apiKeyEnvVar: json['apiKeyEnvVar'] as String? ?? 'FAL_KEY',
      defaultModel: json['defaultModel'] as String?,
      timeout: Duration(seconds: json['timeout'] as int? ?? 60),
      maxRetries: json['maxRetries'] as int? ?? 3,
    );
  }
}

/// Configuration for image generation
class ImageGenerationConfig {
  const ImageGenerationConfig({
    this.enabled = true,
    this.defaultProvider = 'fal',
    this.providers = const [
      ImageGenerationProvider(
        name: 'fal',
        baseUrl: 'https://fal.run/fast-sdxl',
        apiKeyEnvVar: 'FAL_KEY',
        defaultModel: 'fast-sdxl',
      ),
    ],
    this.outputDirectory = 'images',
    this.maxImageSize = 10 * 1024 * 1024, // 10MB
    this.allowedFormats = const ['png', 'jpg', 'jpeg', 'webp'],
    this.watermarkEnabled = false,
    this.watermarkText = 'Generated by Tiko-Agent',
  });

  final bool enabled;
  final String defaultProvider;
  final List<ImageGenerationProvider> providers;
  final String outputDirectory;
  final int maxImageSize;
  final List<String> allowedFormats;
  final bool watermarkEnabled;
  final String watermarkText;

  /// Get provider by name
  ImageGenerationProvider? getProvider(String name) {
    return providers.firstWhere(
      (p) => p.name == name,
      orElse: () => throw ArgumentError('Provider not found: $name'),
    );
  }

  Map<String, dynamic> toJson() => {
        'enabled': enabled,
        'defaultProvider': defaultProvider,
        'providers': providers.map((p) => p.toJson()).toList(),
        'outputDirectory': outputDirectory,
        'maxImageSize': maxImageSize,
        'allowedFormats': allowedFormats,
        'watermarkEnabled': watermarkEnabled,
        'watermarkText': watermarkText,
      };

  factory ImageGenerationConfig.fromJson(Map<String, dynamic> json) {
    return ImageGenerationConfig(
      enabled: json['enabled'] as bool? ?? true,
      defaultProvider: json['defaultProvider'] as String? ?? 'fal',
      providers: (json['providers'] as List<dynamic>? ?? [])
          .map((p) => ImageGenerationProvider.fromJson(p as Map<String, dynamic>))
          .toList(),
      outputDirectory: json['outputDirectory'] as String? ?? 'images',
      maxImageSize: json['maxImageSize'] as int? ?? 10 * 1024 * 1024,
      allowedFormats: (json['allowedFormats'] as List<dynamic>? ?? [])
          .map((f) => f.toString())
          .toList(),
      watermarkEnabled: json['watermarkEnabled'] as bool? ?? false,
      watermarkText: json['watermarkText'] as String? ?? 'Generated by Tiko-Agent',
    );
  }
}

/// Image generation provider (FAL.ai implementation)
class FalImageGenerationProvider implements ImageProvider {
  FalImageGenerationProvider({
    required this.apiKey,
    this.baseUrl = 'https://fal.run',
    this.timeout = const Duration(seconds: 60),
    this.maxRetries = 3,
    this.httpClient,
  });

  final String apiKey;
  final String baseUrl;
  final Duration timeout;
  final int maxRetries;
  final http.Client? httpClient;

  @override
  String get name => 'fal';

  @override
  Future<ImageGenerationResult> generateImage({
    required String prompt,
    String? model,
    String? negativePrompt,
    int? width,
    int? height,
    int? steps,
    double? guidanceScale,
    int? seed,
    String? style,
    String? outputFormat,
  }) async {
    final client = httpClient ?? http.Client();
    
    try {
      // Build the request
      final requestBody = <String, dynamic>{
        'prompt': prompt,
        'log': true,
      };
      
      // Add optional parameters
      if (negativePrompt != null) {
        requestBody['negative_prompt'] = negativePrompt;
      }
      if (width != null) {
        requestBody['width'] = width;
      }
      if (height != null) {
        requestBody['height'] = height;
      }
      if (steps != null) {
        requestBody['num_inference_steps'] = steps;
      }
      if (guidanceScale != null) {
        requestBody['guidance_scale'] = guidanceScale;
      }
      if (seed != null) {
        requestBody['seed'] = seed;
      }
      if (style != null) {
        requestBody['style'] = style;
      }
      
      // Use the specified model or default to fast-sdxl
      final modelName = model ?? 'fast-sdxl';
      final url = '$baseUrl/$modelName';
      
      final response = await client.post(
        Uri.parse(url),
        headers: {
          'Authorization': 'Key $apiKey',
          'Content-Type': 'application/json',
        },
        body: jsonEncode(requestBody),
      ).timeout(timeout);
      
      if (response.statusCode == 200) {
        // Parse the response
        final imageBytes = response.bodyBytes;
        
        return ImageGenerationResult(
          success: true,
          imageBytes: imageBytes,
          model: modelName,
          provider: name,
          width: width,
          height: height,
          prompt: prompt,
        );
      } else {
        return ImageGenerationResult(
          success: false,
          error: 'FAL API error: ${response.statusCode} - ${response.body}',
          provider: name,
          model: modelName,
        );
      }
    } catch (e) {
      return ImageGenerationResult(
        success: false,
        error: 'Failed to generate image: ${e.toString()}',
        provider: name,
        model: model,
      );
    } finally {
      if (httpClient == null) {
        client.close();
      }
    }
  }

  @override
  Future<List<String>> listModels() async {
    // FAL.ai supported models
    return [
      'fast-sdxl',
      'flux-dev',
      'flux-schnell',
      'gpt-image-1.5',
      'gpt-image-2',
      'nano-banana-pro',
      'ideogram-v3',
      'recraft-v4-pro',
      'qwen',
      'z-image-turbo',
      'krea-v2-medium',
      'krea-v2-large',
    ];
  }
}

/// Abstract interface for image generation providers
abstract class ImageProvider {
  String get name;

  Future<ImageGenerationResult> generateImage({
    required String prompt,
    String? model,
    String? negativePrompt,
    int? width,
    int? height,
    int? steps,
    double? guidanceScale,
    int? seed,
    String? style,
    String? outputFormat,
  });

  Future<List<String>> listModels();
}

/// Result of image generation
class ImageGenerationResult {
  const ImageGenerationResult({
    required this.success,
    this.imageBytes,
    this.imagePath,
    this.model,
    this.provider,
    this.width,
    this.height,
    this.prompt,
    this.error,
    this.generationTime,
  });

  final bool success;
  final Uint8List? imageBytes;
  final String? imagePath;
  final String? model;
  final String? provider;
  final int? width;
  final int? height;
  final String? prompt;
  final String? error;
  final Duration? generationTime;

  /// Get the image as base64
  String? get imageBase64 {
    if (imageBytes == null) return null;
    return base64Encode(imageBytes!);
  }

  /// Get the image size in bytes
  int get imageSize => imageBytes?.length ?? 0;

  Map<String, dynamic> toJson() => {
        'success': success,
        'model': model,
        'provider': provider,
        'width': width,
        'height': height,
        'prompt': prompt,
        'error': error,
        'imageSize': imageSize,
        'generationTime': generationTime?.inMilliseconds,
      };
}

/// Tool for generating images from text prompts
class ImageGenerationTool implements Tool {
  ImageGenerationTool({
    required this.provider,
    required this.config,
    this.outputDirectory,
    this.maxRetries = 3,
  });

  final ImageProvider provider;
  final ImageGenerationConfig config;
  final String? outputDirectory;
  final int maxRetries;

  String get name => 'generate_image';

  String get description =>
      'Generate images from text prompts using various AI models. '
      'Supports FAL.ai with models like FLUX 2, GPT-Image, Ideogram, Recraft, and more.';

  @override
  ToolSpec get spec => ToolSpec(
        name: name,
        description: description,
        inputSchema: {
          'type': 'object',
          'properties': {
            'prompt': {
              'type': 'string',
              'description': 'The text prompt describing the image to generate',
              'minLength': 1,
            },
            'model': {
              'type': 'string',
              'description': 'The model to use for generation',
              'enum': [
                'fast-sdxl',
                'flux-dev',
                'flux-schnell',
                'gpt-image-1.5',
                'gpt-image-2',
                'nano-banana-pro',
                'ideogram-v3',
                'recraft-v4-pro',
                'qwen',
                'z-image-turbo',
                'krea-v2-medium',
                'krea-v2-large',
              ],
            },
            'negative_prompt': {
              'type': 'string',
              'description': 'What to exclude from the image',
            },
            'width': {
              'type': 'integer',
              'description': 'Width of the image in pixels (default: 1024)',
              'minimum': 256,
              'maximum': 2048,
            },
            'height': {
              'type': 'integer',
              'description': 'Height of the image in pixels (default: 1024)',
              'minimum': 256,
              'maximum': 2048,
            },
            'steps': {
              'type': 'integer',
              'description': 'Number of inference steps (default: 30)',
              'minimum': 10,
              'maximum': 100,
            },
            'guidance_scale': {
              'type': 'number',
              'description': 'Guidance scale for generation (default: 7.0)',
              'minimum': 1.0,
              'maximum': 20.0,
            },
            'seed': {
              'type': 'integer',
              'description': 'Random seed for reproducible generation',
            },
            'style': {
              'type': 'string',
              'description': 'Style preset for the image',
            },
            'save_to_file': {
              'type': 'boolean',
              'description': 'Whether to save the image to a file (default: true)',
            },
            'output_format': {
              'type': 'string',
              'description': 'Output format for the image',
              'enum': ['png', 'jpg', 'jpeg', 'webp'],
              'default': 'png',
            },
          },
          'required': ['prompt'],
        },
        risk: 'medium',
        parallelSafe: false,
      );

  @override
  Future<ToolResult> run(Map<String, dynamic> args, ToolContext ctx) async {
    final startTime = DateTime.now();
    
    try {
      // Parse arguments
      final prompt = args['prompt'] as String? ?? '';
      if (prompt.isEmpty) {
        return ToolResult(
          callId: '',
          content: jsonEncode({'success': false, 'error': 'Prompt is required'}),
          isError: true,
        );
      }

      final model = args['model'] as String?;
      final negativePrompt = args['negative_prompt'] as String?;
      final width = args['width'] as int? ?? 1024;
      final height = args['height'] as int? ?? 1024;
      final steps = args['steps'] as int?;
      final guidanceScale = args['guidance_scale'] as double?;
      final seed = args['seed'] as int?;
      final style = args['style'] as String?;
      final saveToFile = args['save_to_file'] as bool? ?? true;
      final outputFormat = args['output_format'] as String? ?? 'png';

      // Generate the image
      final result = await provider.generateImage(
        prompt: prompt,
        model: model,
        negativePrompt: negativePrompt,
        width: width,
        height: height,
        steps: steps,
        guidanceScale: guidanceScale,
        seed: seed,
        style: style,
        outputFormat: outputFormat,
      );

      if (!result.success) {
        return ToolResult(
          callId: '',
          content: jsonEncode(result.toJson()),
          isError: true,
        );
      }

      // Save to file if requested
      String? imagePath;
      if (saveToFile && result.imageBytes != null) {
        imagePath = await _saveImage(
          result.imageBytes!,
          prompt,
          model,
          outputFormat,
        );
      }

      // Update result with path
      final finalResult = ImageGenerationResult(
        success: result.success,
        imageBytes: result.imageBytes,
        imagePath: imagePath ?? result.imagePath,
        model: result.model,
        provider: result.provider,
        width: result.width,
        height: result.height,
        prompt: result.prompt,
        generationTime: DateTime.now().difference(startTime),
      );

      return ToolResult(
        callId: '',
        content: jsonEncode(finalResult.toJson()),
        isError: false,
      );
    } catch (e) {
      return ToolResult(
        callId: '',
        content: jsonEncode({
          'success': false,
          'error': e.toString(),
        }),
        isError: true,
      );
    }
  }

  /// Save image to file
  Future<String> _saveImage(
    Uint8List imageBytes,
    String prompt,
    String? model,
    String format,
  ) async {
    final dir = Directory(outputDirectory ?? config.outputDirectory);
    if (!await dir.exists()) {
      await dir.create(recursive: true);
    }

    // Generate filename
    final timestamp = DateTime.now().millisecondsSinceEpoch;
    final safePrompt = prompt
        .replaceAll(RegExp(r'[^a-zA-Z0-9\s]'), '_')
        .replaceAll(RegExp(r'\s+'), '_')
        .toLowerCase();
    
    final filename = '${timestamp}_${safePrompt.substring(0, min(50, safePrompt.length))}_${model ?? 'unknown'}.${format}';
    final path = p.join(dir.path, filename);

    // Save the file
    final file = File(path);
    await file.writeAsBytes(imageBytes);

    return path;
  }

  /// List available models
  Future<List<String>> listModels() async {
    return await provider.listModels();
  }
}

/// Factory for creating image generation tools
class ImageGenerationToolFactory {
  static Tool create({
    String provider = 'fal',
    String? apiKey,
    String? outputDirectory,
  }) {
    if (provider.toLowerCase() == 'fal') {
      if (apiKey == null || apiKey.isEmpty) {
        throw ArgumentError('FAL API key is required for FAL provider');
      }
      
      return ImageGenerationTool(
        provider: FalImageGenerationProvider(apiKey: apiKey),
        config: ImageGenerationConfig(
          defaultProvider: 'fal',
          outputDirectory: outputDirectory ?? 'images',
        ),
        outputDirectory: outputDirectory,
      );
    }
    
    throw ArgumentError('Unsupported provider: $provider');
  }
}

